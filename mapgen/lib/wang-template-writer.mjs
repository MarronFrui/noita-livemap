// Wang template ENCODER — mirror of buildTileset's canonical walk (corner mode).
// Writes a valid stb_hbwang corner-type template PNG with a unique marker RGB
// painted over each tile's whole content (for in-game spawn readout), plus the
// matching Lua registration file for the lab mod. Self-validates by parsing
// the written template back with buildTileset and comparing constraint sets.

import fs from "node:fs";
import { writePng } from "./images.mjs";

// marker RGB for tile index — 16+ distinct, bright, deterministic
export const markerOf = (idx) => [255, 16 + idx * 14, 255 - idx * 14];
export const markerHex = (idx) =>
  "ff" + markerOf(idx).map((v) => v.toString(16).padStart(2, "0")).join("");

export function makeLabTemplate({ numColor = [2, 1, 2, 1], s = 4, varyX = 1, varyY = 1 } = {}) {
  const [nc0, nc1, nc2, nc3] = numColor;
  // per-row tile counts mirror the reader's loops (vary must be >= 1)
  const w = Math.max(varyX * nc3 * nc2 * nc1 * (2 * s + 3), varyY * nc2 * nc3 * nc0 * (s + 3)) + 2;
  const hRows = nc2 * nc1 * nc0 * varyY;
  const vRows = nc3 * nc0 * nc1 * varyX;
  const h = 2 + hRows * (s + 3) + 2 + vRows * (2 * s + 3) + 2;

  const rgba = new Uint8Array(w * h * 4);
  const setPx = (x, y, rgb) => {
    const i = 4 * (y * w + x);
    rgba[i] = rgb[0]; rgba[i + 1] = rgb[1]; rgba[i + 2] = rgb[2]; rgba[i + 3] = 255;
  };

  // header: last 9 RGB bytes of row 0: byte(w*3-1-i) = hdr[i] ^ (i*55)
  // NOTE: 3 bytes share each pixel — collect per-pixel, paint once each.
  const hdr = [nc0, nc1, nc2, nc3, varyX, varyY, s, 0xc0, 0];
  const hdrPx = new Map(); // px -> [r,g,b]
  for (let i = 0; i < 9; i++) {
    const b = w * 3 - 1 - i;
    const px = Math.floor(b / 3);
    const ch = b % 3;
    const v = (hdr[i] ^ (i * 55)) & 0xff; // uint8 truncation — reader applies the same mask
    if (!hdrPx.has(px)) hdrPx.set(px, [0, 0, 0]);
    hdrPx.get(px)[ch] = v;
  }
  for (const [px, rgb] of hdrPx) setPx(px, 0, rgb);

  const tiles = [];
  // h-section — order mirrors buildTileset exactly
  let ypos = 2;
  for (let k = 0; k < nc2; k++)
    for (let j = 0; j < nc1; j++)
      for (let i = 0; i < nc0; i++)
        for (let q = 0; q < varyY; q++) {
          let xpos = 0;
          for (let v = 0; v < varyX; v++)
            for (let cc = 0; cc < nc3; cc++)
              for (let bb = 0; bb < nc2; bb++)
                for (let aa = 0; aa < nc1; aa++) {
                  const idx = tiles.length;
                  const m = markerOf(idx);
                  for (let pj = 0; pj < s; pj++)
                    for (let pi = 0; pi < 2 * s; pi++)
                      setPx(xpos + 1 + pi, ypos + 1 + pj, m);
                  tiles.push({ idx, isH: true, a: aa, b: bb, c: cc, d: i, e: j, f: k, marker: m });
                  xpos += 2 * s + 3;
                }
          ypos += s + 3;
        }
  // v-section
  ypos += 2;
  for (let k = 0; k < nc3; k++)
    for (let j = 0; j < nc0; j++)
      for (let i = 0; i < nc1; i++)
        for (let q = 0; q < varyX; q++) {
          let xpos = 0;
          for (let v = 0; v < varyY; v++)
            for (let cc = 0; cc < nc2; cc++)
              for (let bb = 0; bb < nc3; bb++)
                for (let aa = 0; aa < nc0; aa++) {
                  const idx = tiles.length;
                  const m = markerOf(idx);
                  for (let pj = 0; pj < 2 * s; pj++)
                    for (let pi = 0; pi < s; pi++)
                      setPx(xpos + 1 + pi, ypos + 1 + pj, m);
                  tiles.push({ idx, isH: false, a: aa, b: bb, c: cc, d: i, e: j, f: k, marker: m });
                  xpos += s + 3;
                }
          ypos += 2 * s + 3;
        }

  return { rgba, tiles, width: w, height: h, numColor: [nc0, nc1, nc2, nc3], s, varyX, varyY };
}

export function writeLabPng(outPath, opts) {
  const t = makeLabTemplate(opts);
  writePng(outPath, t.width, t.height, t.rgba);
  return t;
}

export function labLua(tiles) {
  // THIN shim: biome spawn callbacks run in a sandbox WITHOUT io and WITHOUT
  // sight of mod globals — the only shared channel is the game's global store
  // (GlobalsSetValue/Get). Rows are keyed "wanglab_r_<n>"; init.lua (mod
  // context, owns io) drains them into the per-seed CSV.
  const fns = tiles
    .map(
      (t) =>
        `RegisterSpawnFunction(0x${markerHex(t.idx)}, "lab_tile_${t.idx}")\n` +
        `function lab_tile_${t.idx}(x, y) lab_emit("${t.idx},${t.isH ? 1 : 0},${t.a},${t.b},${t.c},${t.d},${t.e},${t.f}", x, y) end`
    )
    .join("\n");
  return `-- GENERATED by mapgen/lib/wang-template-writer.mjs — do not edit
-- Thin shim only: rows go through the game global store (sandbox here has no
-- io and no mod globals). init.lua drains them to the CSV.
dofile_once("data/scripts/biome_scripts.lua")

function lab_emit(fields, x, y)
  local seed = tostring(StatsGetValue("world_seed") or "0")
  local n = tonumber(GlobalsGetValue("wanglab_count", "0") or "0") + 1
  GlobalsSetValue("wanglab_count", tostring(n))
  GlobalsSetValue("wanglab_r_" .. n, seed .. "," .. fields .. "," .. x .. "," .. y)
end

${fns}

RegisterSpawnFunction(0xffffeedd, "lab_chunk_init")
function lab_chunk_init(x, y) lab_emit("chunk", x, y) end
`;
}
